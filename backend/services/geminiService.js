// النموذج قابل للضبط عبر متغيّر البيئة. الافتراضي gemini-2.5-flash (مستقر ومجاني)؛
// يمكن ترقيته إلى gemini-3.5-flash بضبط GEMINI_MODEL دون تعديل الكود.
const GEMINI_MODEL = process.env.GEMINI_MODEL || 'gemini-2.5-flash';
const GEMINI_URL =
  `https://generativelanguage.googleapis.com/v1beta/models/${GEMINI_MODEL}:generateContent`;

// تحويل رسائل المحادثة إلى صيغة محتوى Gemini.
// Gemini يعرف دورين فقط: "user" و "model".
function toGeminiContents(messages) {
  return messages
    .filter((m) => m && typeof m.content === 'string' && m.content.trim())
    .map((m) => ({
      role: m.role === 'assistant' || m.role === 'model' ? 'model' : 'user',
      parts: [{ text: m.content }],
    }));
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// نداء Gemini مع إعادة محاولة قصيرة على الحمل المؤقّت (503).
// لا نعيد المحاولة على 429 (حدّ الكوتا) لأن مدّة الانتظار طويلة — نمرّرها للأعلى فوراً.
async function callGemini(body, attempt = 0) {
  try {
    return await axios.post(GEMINI_URL, body, {
      // المفتاح يُمرَّر في الترويسة بدل الـ query string حتى لا يُسجَّل في السجلّات
      headers: {
        'Content-Type': 'application/json',
        'x-goog-api-key': process.env.GEMINI_API_KEY,
      },
      timeout: 20000, // الفشل سريعاً بدل التعليق إذا تعذّر الوصول إلى Gemini
    });
  } catch (err) {
    const status = err.response?.status;
    if (status === 503 && attempt < 2) {
      await sleep(1500 * (attempt + 1)); // 1.5s ثم 3s
      return callGemini(body, attempt + 1);
    }
    throw err;
  }
}

// بلوك مختصر ببيانات المستخدم يُلحق بالـ system_instruction (للمسجّلين فقط).
function buildUserBlock(u) {
  if (!u) return '';
  return `\n\n【بيانات المستخدم الحالي — استعمليها للإجابة عن أسئلته الشخصية (مثل: كم شجرة زرعت؟ شنو أثري؟) ونادِيه باسمه أحياناً وشجّعيه؛ ولا تذكريها إن ما كانت ذات صلة بالسؤال】
الاسم: ${u.displayName} · عدد أشجاره: ${u.treesCount} · إجمالي CO₂ المختزل: ${u.totalCO2}kg · إجمالي O₂ المنتَج: ${u.totalO2}kg`;
}

/**
 * يرسل تاريخ المحادثة إلى Gemini ويرجّع نص رد "نبتة".
 * عند فشل Gemini يرمي خطأ يحمل `status` (مثل 429) ليُعالَج بلطف في الكنترولر.
 * @param {Array<{role: string, content: string}>} messages
 * @param {{displayName: string, treesCount: number, totalCO2: number, totalO2: number}|null} [userContext]
 * @returns {Promise<string>}
 */
async function generateReply(messages, userContext = null) {
  if (!process.env.GEMINI_API_KEY) {
    throw new Error('GEMINI_API_KEY غير مهيأ في متغيرات البيئة');
  }

  const contents = toGeminiContents(messages);
  if (contents.length === 0) {
    throw new Error('لا توجد رسالة صالحة لإرسالها');
  }

  const systemText = NABTA_SYSTEM_PROMPT + buildUserBlock(userContext);

  let response;
  try {
    response = await callGemini({
      system_instruction: { parts: [{ text: systemText }] },
      contents,
      generationConfig: {
        temperature: 0.7,
        maxOutputTokens: 800,
      },
    });
  } catch (err) {
    // إعادة تغليف الخطأ مع رمز الحالة (429/503/...) حتى يميّزه الكنترولر
    const wrapped = new Error('Gemini API error: ' + (err.response?.status || err.message));
    wrapped.status = err.response?.status;
    throw wrapped;
  }

  const reply =
    response.data?.candidates?.[0]?.content?.parts
      ?.map((p) => p.text)
      .join('')
      .trim();

  if (!reply) {
    throw new Error('Gemini returned no text: ' + JSON.stringify(response.data));
  }

  return reply;
}

module.exports = { generateReply, NABTA_SYSTEM_PROMPT, GEMINI_MODEL };
